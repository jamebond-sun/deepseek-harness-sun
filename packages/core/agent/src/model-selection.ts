/**
 * 由运行时入口点共享的 agent 作用域模型选择。
 * @module @deepseek-ai/dsh-agent/model-selection
 */

import type { Context } from '@deepseek-ai/cordis'
import {
  boundContextSummary,
  createUserMessage,
  type LlmCallConfig,
  type ReasoningEffortId,
} from '@deepseek-ai/dsh-llm'
import type { PreStepDecision } from './runtime-types.ts'
import type { ContextFormed } from '@deepseek-ai/dsh-llm'
declare module '@deepseek-ai/dsh-llm' {
  interface MessageSourceMap {
    'model-selection': { kind: 'model-selection' } & ContextFormed
  }
}

/** 为一个活跃 Agent 选定的完整提供方、模型与可选推理投入度。 */
export interface ModelSelection {
  /** 已注册的提供方路由。 */
  provider: string
  /** 提供方拥有的模型 id。 */
  model: string
  /** 适配器拥有的推理投入度；缺省时为提供方/默认行为。 */
  reasoningEffort?: ReasoningEffortId
}

/** 可变的模型选择，加上为当前 step 捕获的值。 */
export interface ModelSelectionRef {
  /** 为下一个进入提示词组装的 step 选定的模型。 */
  current: ModelSelection | undefined
  /** 当前 step 进入提示词组装时捕获的选择。 */
  assembled: ModelSelection | undefined
}

function sameRoute(left: ModelSelection, right: ModelSelection): boolean {
  return left.provider === right.provider && left.model === right.model
}

function routeLabel(route: ModelSelection, other: ModelSelection): string {
  return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`
}

function modelSwitchNotice(previous: ModelSelection, selected: ModelSelection) {
  const from = routeLabel(previous, selected)
  const to = routeLabel(selected, previous)
  return createUserMessage({
    content: [{
      type: 'text' as const,
      text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
    }],
    source: {
      kind: 'model-selection',
      form: 'notice',
      summary: boundContextSummary(`${from} → ${to}`),
    },
  })
}

/**
 * 将一个可变选择与 Agent 作用域的提示词组装及请求路由耦合。提示词组装在
 * 委托之前快照所选模型，然后将其 provider/model 对与投入度应用到请求配置，
 * 使并发的切换在后续 step 上生效，而不是把两个侧面割裂。缺失的所选投入度
 * 会清除任何继承的投入度，恢复所选模型的提供方/默认行为。
 *
 * provider/model 变更会向下一个准入请求追加一条持久的 user 角色通知。
 * 它将已组装的选择与最新请求头比较；仅投入度的变更和空的无请求决策
 * 不追加通知。请求头持久化之前的失败会在下一个请求上重复该通知。
 *
 * @param agentCtx - 所选 Agent 的作用域上下文。
 * @param selection - 由调用入口点拥有的可变选择。
 * @returns 所有作用域 waterfall 监听器的释放器。
 */
export function installModelSelection(agentCtx: Context, selection: ModelSelectionRef): () => void {
  const disposeAssembly = agentCtx.on('system-prompt/assemble', async (_assembly, _context, next) => {
    const selected = selection.current
    const assembled = await next()
    selection.assembled = selected
    if (selected === undefined) return assembled
    return {
      ...assembled,
      variables: {
        ...assembled.variables,
        provider: selected.provider,
        model: selected.model,
      },
    }
  })
  const disposeRequest = agentCtx.on(
    'agent/request',
    async (_payload, next): Promise<LlmCallConfig> => {
      const resolved = await next()
      const selected = selection.assembled
      if (selected === undefined) return resolved
      const { reasoningEffort: _inheritedEffort, ...withoutInheritedEffort } = resolved
      return {
        ...withoutInheritedEffort,
        provider: selected.provider,
        model: selected.model,
        ...selected.reasoningEffort === undefined
          ? {}
          : { reasoningEffort: selected.reasoningEffort },
      }
    },
  )
  const disposeNotice = agentCtx.on(
    'agent/pre-step',
    async ({ agent, messages, signal, step }, next): Promise<PreStepDecision> => {
      const decision = await next()
      if (decision.kind === 'reject' || signal.aborted) return decision
      // 循环会跳过空的第一个 step 以及被清空的已提议延续。
      if (decision.messages.length === 0 && (step === 1 || messages.length > 0)) return decision
      const selected = selection.assembled
      const previous = agent.session.requestHeader()?.config
      if (selected === undefined || previous === undefined || sameRoute(selected, previous)) return decision
      return { ...decision, messages: [...decision.messages, modelSwitchNotice(previous, selected)] }
    },
    { prepend: true },
  )
  return () => {
    disposeAssembly()
    disposeRequest()
    disposeNotice()
  }
}
